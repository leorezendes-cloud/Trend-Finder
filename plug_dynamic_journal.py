"""Isolated append-only research journal for dynamic pregame Plug decisions.

Not an official pick/grade source. Caller must supply verified quotes and a
decision generated by plug_dynamic_pregame.decide. Atomic O_EXCL first writes
and an advisory file lock serialize concurrent workers on the same host.
"""
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import fcntl

FIELDS=("ats_selected","ats_side","ats_away_line","ou_selected","ou_side",
        "ou_market_total","ou_source","quote_observed_utc","evaluated_utc",
        "kickoff_utc")

def _time(value):
    dt=datetime.fromisoformat(value.replace("Z","+00:00"))
    if dt.tzinfo is None:
        raise ValueError("Timezone required")
    return dt.astimezone(timezone.utc)

def _canonical(data):
    return json.dumps(data,sort_keys=True,separators=(",",":"),allow_nan=False)

def _path(root, game_id):
    if not game_id or not all(c.isalnum() or c in "_-" for c in game_id):
        raise ValueError("Invalid game ID")
    return Path(root)/"plug_dynamic_research"/(game_id+".jsonl")

@contextmanager
def _lock(path):
    path.parent.mkdir(parents=True,exist_ok=True)
    with (path.with_suffix(".lock")).open("a+b") as handle:
        fcntl.flock(handle.fileno(),fcntl.LOCK_EX)
        try: yield
        finally: fcntl.flock(handle.fileno(),fcntl.LOCK_UN)

def read(root,game_id):
    path=_path(root,game_id)
    if not path.is_file(): return []
    entries=[]
    previous="0"*64
    for line in path.read_text(encoding="utf-8").splitlines():
        item=json.loads(line)
        signature=item.pop("sha256")
        if item.get("previous_sha256")!=previous or hashlib.sha256(_canonical(item).encode()).hexdigest()!=signature:
            raise ValueError("Revision history integrity failure")
        item["sha256"]=signature
        entries.append(item)
        previous=signature
    return entries

def append(root,game_id,decision):
    """Add a changed pregame state, or return the existing latest state.

    Idempotent for unchanged states. This journal is deliberately not a source
    for official published picks until the full migration is tested.
    """
    if not all(key in decision for key in FIELDS):
        raise ValueError("Incomplete dynamic decision")
    path=_path(root,game_id)
    with _lock(path):
        history=read(root,game_id)
        proposed={k:decision[k] for k in FIELDS}
        observed=_time(proposed["quote_observed_utc"])
        evaluated=_time(proposed["evaluated_utc"])
        kickoff=_time(proposed["kickoff_utc"])
        if not observed<=evaluated<kickoff:
            raise ValueError("Decision is not verified pregame")
        if history:
            last=history[-1]
            if last["kickoff_utc"]!=proposed["kickoff_utc"]:
                raise ValueError("Kickoff identity changed")
            if evaluated<_time(last["evaluated_utc"]) or observed<_time(last["quote_observed_utc"]):
                raise ValueError("Out-of-order research quote")
            # Exact retries are harmless; do not erase a changed pick with a
            # later quote which has the same resulting decision and line.
            signal=("ats_selected","ats_side","ats_away_line",
                    "ou_selected","ou_side","ou_market_total","ou_source")
            if all(last[k]==proposed[k] for k in signal):
                return last
        payload={"game_id":game_id,"revision":len(history)+1,
                 "previous_sha256":history[-1]["sha256"] if history else "0"*64,
                 **proposed}
        payload["sha256"]=hashlib.sha256(_canonical(payload).encode()).hexdigest()
        with path.open("a",encoding="utf-8") as output:
            output.write(_canonical(payload)+"\n")
            output.flush()
            os.fsync(output.fileno())
        return payload
